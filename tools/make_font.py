#!/usr/bin/env python3
"""Generates runtime/src/font_data.h: a 1-bit 8x16 bitmap font (ASCII 32..126) for the in-game menu,
rasterized from DejaVu Sans Mono (Bitstream Vera licence: free to embed). Needs Pillow."""
import sys
from PIL import Image, ImageDraw, ImageFont
ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
out = sys.argv[2] if len(sys.argv) > 2 else "runtime/src/font_data.h"
W, H = 8, 16
font = ImageFont.truetype(ttf, 13)
rows = []
for ch in range(32, 127):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    bbox = font.getbbox(chr(ch))
    x = (W - (bbox[2] - bbox[0])) // 2 - bbox[0]
    d.text((x, 0), chr(ch), font=font, fill=255)
    px = im.load()
    for y in range(H):
        b = 0
        for xx in range(W):
            if px[xx, y] >= 110: b |= 0x80 >> xx
        rows.append(b)
with open(out, "w") as f:
    f.write("// Generated by tools/make_font.py from DejaVu Sans Mono Bold (Bitstream Vera licence). 8x16, ASCII 32..126.\n")
    f.write("#pragma once\nstatic const unsigned char kFont8x16[95 * 16] = {\n")
    for i in range(0, len(rows), 16):
        f.write("    " + ",".join("0x%02x" % v for v in rows[i:i + 16]) + ",  // '%s'\n" % chr(32 + i // 16).replace("\\", "backslash"))
    f.write("};\n")
print("wrote", out)
