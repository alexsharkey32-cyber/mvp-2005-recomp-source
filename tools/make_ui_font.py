#!/usr/bin/env python3
"""Generates runtime/src/ui_font.h: anti-aliased glyph atlases (8-bit coverage) for the launcher and menu.
Faces: Poppins Regular / Bold for text (SIL Open Font License) and TeX Gyre Heros Condensed Bold Italic for
headings (GUST Font License): free to use and embed. Symbols those faces lack (arrows, check mark) come from
DejaVu Sans (Bitstream Vera licence). Drawn at 56 px (the runtime mipmaps the atlas for small text). Needs Pillow.
usage: make_ui_font.py [out]"""
import sys
from PIL import Image, ImageDraw, ImageFont

GYRE = "/usr/share/texmf/fonts/opentype/public/tex-gyre"
POPPINS = "/usr/share/fonts/truetype/google-fonts"
DEJAVU = "/usr/share/fonts/truetype/dejavu"
out = sys.argv[1] if len(sys.argv) > 1 else "runtime/src/ui_font.h"
SIZE = 56
EXTRA = [0x00D7, 0x2026, 0x2022, 0x2190, 0x2191, 0x2192, 0x2193, 0x25B8, 0x2713, 0x00B0, 0x2013, 0x266A, 0x25CF, 0x2039, 0x203A, 0x00E9, 0x00B7, 0x2014, 0x25B2, 0x25BC, 0x25C0, 0x25B6, 0x2605, 0x2715, 0x23CE, 0x2699, 0x21BB]
CODES = list(range(32, 127)) + EXTRA
ATLAS_W = 2048

def has_glyph(font, ch):
    """PIL draws .notdef for a missing character: compare with a character no font has"""
    a = font.getmask(ch); b = font.getmask(chr(0x10FFFD))
    return not (a.size == b.size and bytes(a) == bytes(b))
def build(path, name, fallback):
    main = ImageFont.truetype(path, SIZE); fb = ImageFont.truetype(fallback, SIZE)
    ascent, descent = main.getmetrics()
    glyphs = []
    x = y = 2
    row_h = 0
    tiles = []
    for cp in CODES:
        ch = chr(cp)
        font = main if cp < 127 or has_glyph(main, ch) else fb
        bbox = font.getbbox(ch)                 # (l, t, r, b) relative to the drawing origin (top of ascent)
        adv = font.getlength(ch)
        w = max(bbox[2] - bbox[0], 0); h = max(bbox[3] - bbox[1], 0)
        if w == 0 or h == 0:
            glyphs.append((cp, 0, 0, 0, 0, 0, 0, adv)); continue
        if x + w + 2 > ATLAS_W:
            x = 2; y += row_h + 6; row_h = 0
        im = Image.new("L", (w + 2, h + 2), 0)
        ImageDraw.Draw(im).text((1 - bbox[0], 1 - bbox[1]), ch, font=font, fill=255)
        tiles.append((x, y, im))
        glyphs.append((cp, x, y, w + 2, h + 2, bbox[0] - 1, bbox[1] - 1, adv))
        x += w + 8; row_h = max(row_h, h + 2)
    H = y + row_h + 4
    atlas = Image.new("L", (ATLAS_W, H), 0)
    for (tx, ty, im) in tiles: atlas.paste(im, (tx, ty))
    return atlas, glyphs, ascent, descent

with open(out, "w") as f:
    f.write("// Generated by tools/make_ui_font.py from Poppins (SIL OFL), TeX Gyre Heros Condensed (GUST Font License) and\n// DejaVu Sans symbols (Bitstream Vera licence). Do not edit.\n#pragma once\n")
    f.write("struct UiGlyph { unsigned cp; short x, y, w, h, xoff, yoff; float adv; };\n")
    for fname, var, fbname in ((POPPINS + "/Poppins-Regular.ttf", "Regular", "DejaVuSans.ttf"), (POPPINS + "/Poppins-Bold.ttf", "Bold", "DejaVuSans-Bold.ttf"),
                               (GYRE + "/texgyreheroscn-bolditalic.otf", "Display", "DejaVuSansCondensed-Bold.ttf")):
        atlas, glyphs, asc, desc = build(fname, var, DEJAVU + "/" + fbname)
        data = atlas.tobytes()
        # run-length encode zero runs to keep the header small: pairs (count, value) where value==0 runs
        rle = []
        i = 0
        while i < len(data):
            if data[i] == 0:
                j = i
                while j < len(data) and data[j] == 0 and j - i < 255: j += 1
                rle += [0, j - i]; i = j
            else:
                rle.append(data[i]); i += 1
        f.write(f"static const int kFont{var}W = {atlas.width}, kFont{var}H = {atlas.height}, kFont{var}Size = {SIZE}, kFont{var}Ascent = {asc}, kFont{var}Descent = {desc};\n")
        f.write(f"static const UiGlyph kFont{var}Glyphs[{len(glyphs)}] = {{\n")
        for g in glyphs:
            f.write("    {%d,%d,%d,%d,%d,%d,%d,%.3ff},\n" % g)
        f.write("};\n")
        f.write(f"// RLE: a 0 byte is followed by the length of a run of zeros\nstatic const unsigned char kFont{var}Rle[{len(rle)}] = {{\n")
        for k in range(0, len(rle), 40):
            f.write("    " + ",".join(str(v) for v in rle[k:k + 40]) + ",\n")
        f.write("};\n")
print("wrote", out)
